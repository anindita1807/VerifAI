"""
report_generator.py - Builds the downloadable Markdown and CSV reports.

The report keeps three things clearly apart:
  1. Deterministic Python findings and the rule-based score.
  2. The LLM-generated explanation (only if one was actually produced).
  3. Limitations, missing evidence and the disclaimer.
"""

from __future__ import annotations

import csv
import io
from typing import Any

from tools import INDICATOR_LABELS

DISCLAIMER = (
    "This application is an educational transaction-analysis prototype. Its risk score is a rule-based "
    "indicator, not a probability of fraud. All findings require human review."
)

MODE_LABELS = {"llm": "LLM Agent Mode (Groq)", "rule_based": "Rule-Based Demo Mode (no LLM used)"}


def _md_escape(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def build_markdown_report(result: dict[str, Any]) -> str:
    """Return the full investigation report as Markdown text."""
    lines: list[str] = []
    add = lines.append
    risk = result.get("risk") or {}

    add("# VerifAI - Investigation Report")
    add("")
    add(f"> {DISCLAIMER}")
    add("")
    add("## 1. Investigation details")
    add("")
    add(f"- Investigation ID: {result['investigation_id']}")
    add(f"- Date and time: {result['created_at']}")
    add(f"- Dataset: {result.get('dataset_label', '')}")
    add(f"- Transactions analysed: {result.get('n_transactions', 0)}")
    add(f"- Login events supplied: {result.get('n_login_events', 0)}")
    add(f"- Operating mode: {MODE_LABELS.get(result['mode'], result['mode'])}")
    if result.get("model"):
        add(f"- LLM model: {result['model']} (via Groq)")
    add(f"- LLM requests made: {result.get('llm_calls', 0)}")
    add(f"- Status: {result['status']}")
    if result.get("error"):
        add(f"- Error: {result['error']}")
    add("")

    summary = result.get("dataset_summary") or {}
    if summary:
        add("## 2. Dataset summary")
        add("")
        add(f"- Accounts: {summary.get('account_count')}")
        add(f"- Date range: {summary.get('date_range', ['', ''])[0]} to {summary.get('date_range', ['', ''])[1]}")
        add(f"- Amount range: INR {summary.get('amount_min'):,} to INR {summary.get('amount_max'):,} (median INR {summary.get('amount_median'):,})")
        add(f"- Login data available: {'Yes' if summary.get('login_data_available') else 'No'}")
        add("")

    if risk:
        add("## 3. Rule-based risk score (deterministic Python)")
        add("")
        add(f"**Score: {risk['score']} / 100 - {risk['category']}**")
        add("")
        add("| Indicator | Weight | Points added | Note |")
        add("|---|---|---|---|")
        for c in risk.get("contributions", []):
            add(f"| {_md_escape(c['label'])} | {c['weight']} | {c['points']} | {_md_escape(c['note'])} |")
        if not risk.get("contributions"):
            add("| No indicators found | - | 0 | - |")
        if risk.get("uncapped_score", 0) > 100:
            add("")
            add(f"The raw total was {risk['uncapped_score']}; it is capped at 100.")
        add("")

    add("## 4. Tools selected and executed")
    add("")
    reasons = result.get("tool_reasons", {})
    for name in result.get("executed_tools", []):
        add(f"- {name} - reason: {reasons.get(name, 'n/a')}")
    if result.get("rejected_tools"):
        add(f"- Rejected (not on the allowlist): {', '.join(result['rejected_tools'])}")
    if not result.get("executed_tools"):
        add("- No tools were executed.")
    add("")

    add("## 5. Findings and evidence (deterministic Python)")
    add("")
    any_finding = False
    for tool in result.get("tool_results", []):
        add(f"### {tool['tool_name']} ({tool['status']})")
        add("")
        add(tool.get("explanation", ""))
        add("")
        for f in tool.get("findings", []):
            any_finding = True
            label = INDICATOR_LABELS.get(f["indicator"], f["indicator"])
            add(f"- **{label}** - account {f['account_id']}: {f['explanation']}")
            add(f"  - Evidence IDs: {', '.join(f['evidence_ids'])}")
        if not tool.get("findings"):
            add("- No findings from this tool.")
        add("")
    if not any_finding and not result.get("tool_results"):
        add("No findings were produced.")
        add("")

    add("## 6. Explanation")
    add("")
    explanation = result.get("llm_explanation")
    if explanation:
        add(f"*Generated by the LLM ({result.get('model')}) from the Python findings above.*")
        add("")
        add(explanation["summary"])
        add("")
        for obs in explanation.get("key_observations", []):
            ids = f" (evidence: {', '.join(obs['evidence_ids'])})" if obs["evidence_ids"] else ""
            add(f"- {obs['statement']}{ids}")
        if explanation.get("recommended_actions"):
            add("")
            add("LLM-suggested actions:")
            for a in explanation["recommended_actions"]:
                add(f"- {a}")
        if explanation.get("caveats"):
            add("")
            add("LLM-noted caveats:")
            for c in explanation["caveats"]:
                add(f"- {c}")
    elif result.get("rule_based_summary"):
        add("*Template summary written by Python rules. No LLM was used.*")
        add("")
        add(result["rule_based_summary"])
    elif result.get("llm_explanation_error"):
        add(f"No LLM explanation: {result['llm_explanation_error']}")
    else:
        add("No explanation was generated.")
    add("")

    add("## 7. Recommended next steps (rule-based)")
    add("")
    for step in result.get("next_steps", []) or ["Review the error above and run the investigation again."]:
        add(f"- {step}")
    add("")

    add("## 8. Missing evidence and limitations")
    add("")
    for lim in result.get("limitations", []):
        add(f"- {lim}")
    add("- The data is synthetic and the thresholds are illustrative, not industry-standard or statistically validated.")
    add("")

    add("## 9. Agent execution trace")
    add("")
    add("| Step | Node | Actor | Status | Detail |")
    add("|---|---|---|---|---|")
    for t in result.get("trace", []):
        add(f"| {t['step']} | {t['node']} | {_md_escape(t['actor'])} | {t['status']} | {_md_escape(t['detail'])} |")
    add("")
    add("## 10. Reviewer decision")
    add("")
    add("- Reviewer name: ____________________")
    add("- Decision: ____________________")
    add("- Notes: ____________________")
    add("")
    add("---")
    add(DISCLAIMER)
    return "\n".join(lines) + "\n"


def build_findings_csv(result: dict[str, Any]) -> str:
    """One row per finding, for spreadsheets."""
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["investigation_id", "tool", "indicator", "indicator_label", "account_id", "evidence_ids", "explanation"])
    for tool in result.get("tool_results", []):
        for f in tool.get("findings", []):
            writer.writerow(
                [
                    result["investigation_id"],
                    tool["tool_name"],
                    f["indicator"],
                    INDICATOR_LABELS.get(f["indicator"], f["indicator"]),
                    f["account_id"],
                    ";".join(f["evidence_ids"]),
                    f["explanation"],
                ]
            )
    return buffer.getvalue()
