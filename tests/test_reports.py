"""Tests for the Markdown and CSV report generator."""

import csv
import io

from agent import MODE_LLM, MODE_RULE_BASED, run_investigation
from report_generator import DISCLAIMER, build_findings_csv, build_markdown_report


class FakeLLM:
    model = "fake-model"

    def select_tools(self, summary, descriptions):
        return {"tools": [{"name": n, "reason": "test"} for n in descriptions]}

    def explain(self, evidence):
        return {
            "summary": "LLM summary text.",
            "key_observations": [{"statement": "Large transfer.", "evidence_ids": ["TXN-S007"]}],
            "recommended_actions": ["Verify."],
            "caveats": ["Synthetic data."],
        }


def test_rule_based_report_contains_required_sections(suspicious_data):
    result = run_investigation(*suspicious_data, "Suspicious demo", MODE_RULE_BASED)
    report = build_markdown_report(result)
    for text in [
        result["investigation_id"],
        "Score: 100 / 100 - Critical",
        "Findings and evidence (deterministic Python)",
        "Template summary written by Python rules. No LLM was used.",
        "Recommended next steps",
        "Missing evidence and limitations",
        "Agent execution trace",
        DISCLAIMER,
        "TXN-S007",
    ]:
        assert text in report
    assert "Generated by the LLM" not in report


def test_llm_report_labels_model_text_separately(suspicious_data):
    result = run_investigation(*suspicious_data, "Suspicious demo", MODE_LLM, llm=FakeLLM())
    report = build_markdown_report(result)
    assert "Generated by the LLM (fake-model)" in report
    assert "LLM summary text." in report
    assert "No LLM was used" not in report


def test_report_for_missing_login_data_lists_the_limitation(ambiguous_data):
    result = run_investigation(*ambiguous_data, "Ambiguous demo", MODE_RULE_BASED)
    report = build_markdown_report(result)
    assert "Login evidence was unavailable" in report
    assert "Login events supplied: 0" in report


def test_findings_csv_has_one_row_per_finding(suspicious_data):
    result = run_investigation(*suspicious_data, "Suspicious demo", MODE_RULE_BASED)
    rows = list(csv.DictReader(io.StringIO(build_findings_csv(result))))
    assert len(rows) == 6
    assert {r["indicator"] for r in rows} >= {"repeated_failed_logins", "unusual_amount_vs_history"}
